/// Old id to new id (or ids) when a setting is deliberately renamed or
/// merged. Empty: the reorg moved settings between pages without renaming
/// or merging any of them.
const Map<String, String> _renamedOrMergedIds = {};

void main() {
  test('no setting went missing in the reorg', () {
    final current = allSettingsSearchEntries.map((e) => e.id).toSet();
    final frozen = _preReorgIds.toSet();
    final renamed = _renamedOrMergedIds.keys.toSet();
    expect(
      current,
      frozen.difference(renamed),
      reason: 'every pre-reorg setting is still searchable after the move',
    );
    expect(
      frozen.difference(current),
      renamed,
      reason: 'only explicitly recorded renames may leave the set',
    );
  });
}
